// projectspec compiles explicit identity envelopes and route inventory from the
// authoritative OpenAPI contract. Opaque JSON/schema/artifact fields are leaves.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"gopkg.in/yaml.v3"
	"os"
	"sort"
	"strings"
)

type object = map[string]any

func main() {
	if len(os.Args) > 1 {
		if err := os.Chdir(os.Args[1]); err != nil {
			panic(err)
		}
	}
	raw, e := os.ReadFile("openapi/jobdb-runtime.yaml")
	if e != nil {
		panic(e)
	}
	var spec object
	if e = yaml.Unmarshal(raw, &spec); e != nil {
		panic(e)
	}
	components := spec["components"].(object)
	schemas := components["schemas"].(object)
	var affected func(any, map[string]bool) bool
	affected = func(v any, seen map[string]bool) bool {
		m, ok := v.(object)
		if !ok {
			return false
		}
		if r, ok := m["$ref"].(string); ok {
			n := strings.TrimPrefix(r, "#/components/schemas/")
			if seen[n] {
				return false
			}
			seen[n] = true
			return affected(schemas[n], seen)
		}
		if ps, ok := m["properties"].(object); ok {
			if ps["tenantId"] != nil {
				return true
			}
			for _, v := range ps {
				if affected(v, seen) {
					return true
				}
			}
		}
		if xs, ok := m["allOf"].([]any); ok {
			for _, x := range xs {
				if affected(x, seen) {
					return true
				}
			}
		}
		return affected(m["items"], seen)
	}
	var properties func(object) object
	properties = func(m object) object {
		out := object{}
		if ref, ok := m["$ref"].(string); ok {
			return properties(schemas[strings.TrimPrefix(ref, "#/components/schemas/")].(object))
		}
		if xs, ok := m["allOf"].([]any); ok {
			for _, x := range xs {
				if child, ok := x.(object); ok {
					for k, v := range properties(child) {
						out[k] = v
					}
				}
			}
		}
		if ps, ok := m["properties"].(object); ok {
			for k, v := range ps {
				out[k] = v
			}
		}
		return out
	}
	// Keep inline envelopes explicit as well as named ones.
	defs := map[string]string{}
	var shape func(any, string) string
	shape = func(v any, name string) string {
		m, ok := v.(object)
		if !ok {
			return ""
		}
		if ref, ok := m["$ref"].(string); ok {
			n := strings.TrimPrefix(ref, "#/components/schemas/")
			if strings.HasPrefix(n, "Project") {
				n = strings.TrimPrefix(n, "Project")
			}
			if !affected(schemas[n], map[string]bool{}) {
				return ""
			}
			if _, ok := defs[n]; !ok {
				defs[n] = ""
				shape(schemas[n], n)
			}
			return n
		}
		if !affected(m, map[string]bool{}) {
			return ""
		}
		if item := shape(m["items"], name+"Item"); item != "" {
			defs[name] = fmt.Sprintf("{element:%q}", item)
			return name
		}
		ps := properties(m)
		identity := ps["tenantId"] != nil
		keys := []string{}
		for k := range ps {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fields := []string{}
		for _, k := range keys {
			if k == "tenantId" {
				continue
			}
			if child := shape(ps[k], name+strings.Title(k)); child != "" {
				fields = append(fields, fmt.Sprintf("%q:%q", k, child))
			}
		}
		defs[name] = fmt.Sprintf("{identity:%v, fields:map[string]string{%s}}", identity, strings.Join(fields, ","))
		return name
	}
	var resolve func(any) object
	resolve = func(v any) object {
		m, _ := v.(object)
		if ref, ok := m["$ref"].(string); ok {
			parts := strings.Split(ref, "/")
			return resolve(components[parts[2]].(object)[parts[3]])
		}
		return m
	}
	bodyShape := func(v any, name string) string {
		m := resolve(v)
		c, _ := m["content"].(object)
		j, _ := c["application/json"].(object)
		return shape(j["schema"], name)
	}
	paths := spec["paths"].(object)
	keys := []string{}
	for p := range paths {
		keys = append(keys, p)
	}
	sort.Strings(keys)
	var routes []string
	for _, p := range keys {
		if !strings.HasPrefix(p, "/v1/tenants/") && p != "/v1/jobs/poll" {
			continue
		}
		item := paths[p].(object)
		for _, method := range []string{"get", "post", "put", "patch", "delete"} {
			op, ok := item[method].(object)
			if !ok {
				continue
			}
			name := op["operationId"].(string)
			req := bodyShape(op["requestBody"], name+"Request")
			responses, _ := op["responses"].(object)
			statuses := []string{}
			for code := range responses {
				statuses = append(statuses, code)
			}
			sort.Strings(statuses)
			var res []string
			for _, code := range statuses {
				if code[0] != '2' {
					continue
				}
				s := bodyShape(responses[code], name+code+"Response")
				if s != "" {
					res = append(res, fmt.Sprintf("%s:%q", code, s))
				}
			}
			routes = append(routes, fmt.Sprintf("{method:%q, path:%q, request:%q, responses:map[int]string{%s}},", strings.ToUpper(method), p, req, strings.Join(res, ",")))
		}
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go run ./internal/projectspec; DO NOT EDIT.\npackage projectwire\nvar schemas=map[string]projectWireSchema{")
	names := []string{}
	for n := range defs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&out, "%q:%s,\n", n, defs[n])
	}
	fmt.Fprintln(&out, "}")
	formatted, e := format.Source(out.Bytes())
	if e != nil {
		panic(e)
	}
	if e = os.WriteFile("pkg/jobdb/internal/projectwire/zz_shapes.go", formatted, 0644); e != nil {
		panic(e)
	}
	out.Reset()
	fmt.Fprintln(&out, "// Code generated by go run ./internal/projectspec; DO NOT EDIT.\npackage remote\nvar projectWireRoutes=[]projectWireRoute{")
	for _, r := range routes {
		fmt.Fprintln(&out, r)
	}
	fmt.Fprintln(&out, "}")
	formatted, e = format.Source(out.Bytes())
	if e != nil {
		panic(e)
	}
	if e = os.WriteFile("pkg/jobdb/runtime/remote/zz_project_routes.go", formatted, 0644); e != nil {
		panic(e)
	}
}
