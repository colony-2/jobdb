// genconsumer derives the retained server bindings from oapi-codegen's complete
// operation inventory. Wire types, codecs and middleware options remain shared.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path"
	"strconv"
)

const retired = "AddGoalCandidate"

var names = map[string]string{
	"ServerInterface":             "ConsumerServerInterface",
	"ServerInterfaceWrapper":      "ConsumerServerInterfaceWrapper",
	"StrictServerInterface":       "ConsumerStrictServerInterface",
	"strictHandler":               "consumerStrictHandler",
	"HandlerFromMux":              "ConsumerHandlerFromMux",
	"HandlerFromMuxWithBaseURL":   "ConsumerHandlerFromMuxWithBaseURL",
	"HandlerWithOptions":          "ConsumerHandlerWithOptions",
	"NewStrictHandler":            "NewConsumerStrictHandler",
	"NewStrictHandlerWithOptions": "NewConsumerStrictHandlerWithOptions",
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	fset := token.NewFileSet()
	source, err := parser.ParseFile(fset, "zz_generated.go", nil, 0)
	if err != nil {
		return err
	}
	out := &ast.File{Name: ast.NewIdent("runtimeapi")}
	methods, wrappers, strictMethods, routes := 0, 0, 0, 0
	for _, decl := range source.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			if d.Tok != token.TYPE || len(d.Specs) != 1 {
				continue
			}
			t := d.Specs[0].(*ast.TypeSpec)
			if _, ok := names[t.Name.Name]; !ok {
				continue
			}
			if iface, ok := t.Type.(*ast.InterfaceType); ok {
				retained := iface.Methods.List[:0]
				removed := 0
				for _, field := range iface.Methods.List {
					if len(field.Names) == 1 && field.Names[0].Name == retired {
						removed++
						continue
					}
					retained = append(retained, field)
				}
				if removed != 1 {
					return fmt.Errorf("%s: expected one retired operation, found %d", t.Name, removed)
				}
				iface.Methods.List = retained
				if methods != 0 && methods != len(retained) {
					return fmt.Errorf("server operation inventories differ")
				}
				methods = len(retained)
			}
			out.Decls = append(out.Decls, d)
		case *ast.FuncDecl:
			if d.Recv != nil {
				ptr, ok := d.Recv.List[0].Type.(*ast.StarExpr)
				if !ok {
					continue
				}
				typ, ok := ptr.X.(*ast.Ident)
				if !ok || (typ.Name != "ServerInterfaceWrapper" && typ.Name != "strictHandler") || d.Name.Name == retired {
					continue
				}
				if typ.Name == "ServerInterfaceWrapper" {
					wrappers++
				} else {
					strictMethods++
				}
			} else if d.Name.Name == "Handler" {
				// Do not rename the unrelated http.Handler type or wrapper.Handler field.
				d.Name.Name = "ConsumerHandler"
			} else if _, ok := names[d.Name.Name]; !ok {
				continue
			}
			if d.Name.Name == "HandlerWithOptions" {
				retained := d.Body.List[:0]
				for _, statement := range d.Body.List {
					isRetired := false
					ast.Inspect(statement, func(n ast.Node) bool {
						if selector, ok := n.(*ast.SelectorExpr); ok && selector.Sel.Name == retired {
							isRetired = true
						}
						return true
					})
					if isRetired {
						routes++
						continue
					}
					retained = append(retained, statement)
				}
				d.Body.List = retained
			}
			out.Decls = append(out.Decls, d)
		}
	}
	if methods == 0 || wrappers != methods || strictMethods != methods || routes != 1 {
		return fmt.Errorf("unexpected generated server shape: methods=%d wrappers=%d strict=%d retired routes=%d", methods, wrappers, strictMethods, routes)
	}
	usedImports := map[string]bool{}
	ast.Inspect(out, func(n ast.Node) bool {
		if selector, ok := n.(*ast.SelectorExpr); ok {
			if qualifier, ok := selector.X.(*ast.Ident); ok {
				usedImports[qualifier.Name] = true
			}
		}
		if id, ok := n.(*ast.Ident); ok {
			if replacement, ok := names[id.Name]; ok {
				id.Name = replacement
			}
		}
		return true
	})
	imports := &ast.GenDecl{Tok: token.IMPORT, Lparen: 1}
	for _, spec := range source.Imports {
		value, _ := strconv.Unquote(spec.Path.Value)
		name := path.Base(value)
		if spec.Name != nil {
			name = spec.Name.Name
		} else if len(name) > 1 && name[0] == 'v' {
			if _, err := strconv.Atoi(name[1:]); err == nil {
				name = path.Base(path.Dir(value))
			}
		}
		if usedImports[name] {
			item := &ast.ImportSpec{Path: &ast.BasicLit{Kind: token.STRING, Value: spec.Path.Value}}
			if spec.Name != nil {
				item.Name = ast.NewIdent(spec.Name.Name)
			}
			imports.Specs = append(imports.Specs, item)
		}
	}
	out.Decls = append([]ast.Decl{imports}, out.Decls...)
	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./genconsumer from zz_generated.go; DO NOT EDIT.\n")
	if err := format.Node(&buf, fset, out); err != nil {
		return err
	}
	return os.WriteFile("zz_consumer_generated.go", buf.Bytes(), 0644)
}
